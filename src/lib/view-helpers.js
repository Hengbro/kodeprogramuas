const { ROMAWI, TERBILANG_KELAS, P5_LEVEL, peringkatKata } = require('./calc');

const BULAN = ['Januari', 'Februari', 'Maret', 'April', 'Mei', 'Juni', 'Juli', 'Agustus', 'September', 'Oktober', 'November', 'Desember'];

function tanggal(iso) {
  if (!iso) return '';
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(iso);
  if (!m) return iso;
  return `${Number(m[3])} ${BULAN[Number(m[2]) - 1]} ${m[1]}`;
}

function angka(n, digits = 0) {
  if (n == null || Number.isNaN(n)) return '';
  return Number(n).toLocaleString('id-ID', { minimumFractionDigits: digits, maximumFractionDigits: digits });
}

function jk(v) {
  return v === 'L' ? 'Laki-laki' : v === 'P' ? 'Perempuan' : '';
}

function semesterLabel(s) {
  return Number(s) === 1 ? '1 (Ganjil)' : '2 (Genap)';
}

function periodLabel(p) {
  return p ? `${p.tahun_pelajaran} — Semester ${Number(p.semester) === 1 ? 'Ganjil' : 'Genap'}` : '-';
}

function ttl(st) {
  return [st.tempat_lahir, tanggal(st.tanggal_lahir)].filter(Boolean).join(', ');
}

module.exports = { tanggal, angka, jk, semesterLabel, periodLabel, ttl, ROMAWI, TERBILANG_KELAS, P5_LEVEL, BULAN, peringkatKata };

